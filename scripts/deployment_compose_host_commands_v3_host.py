"""Fixed read-only host network projection; no caller command or partial coverage."""
import hashlib
import json
import math
import os
from pathlib import Path
import re
import selectors
import stat
import subprocess
import sys
import time

PROFILE='host-network-firewall-v1'
_COMMANDS=(('/usr/sbin/ip','-json','-4','route','show','table','all'),
    ('/usr/sbin/ip','-json','-6','route','show','table','all'),
    ('/usr/sbin/iptables-save',),('/usr/sbin/ip6tables-save',))
_SYSTEMD={
    'docker.service':('/usr/bin/systemctl','--system','show','docker.service','--all',
        '--property=Id,LoadState,ActiveState,SubState,MainPID,ControlGroup,InvocationID'),
    'docker.socket':('/usr/bin/systemctl','--system','show','docker.socket','--all',
        '--property=Id,LoadState,ActiveState,SubState,InvocationID,Listen'),
}
_FORWARD=('/proc/sys/net/ipv4/ip_forward','/proc/sys/net/ipv6/conf/all/forwarding')


def reject():raise ValueError('compose-host-commands-v3-rejected') from None


def _left(deadline):
    if type(deadline) not in (int,float) or not math.isfinite(deadline):reject()
    left=deadline-time.monotonic()
    if not 0<left<=30:reject()
    return left


def _executable(path):
    target=Path(path).resolve(strict=True);info=target.stat()
    if (not stat.S_ISREG(info.st_mode) or info.st_uid!=0 or info.st_mode&0o022
            or not info.st_mode&0o111):reject()
    return str(target),info.st_dev,info.st_ino


def _spawn(argv):
    return subprocess.Popen(argv,stdin=subprocess.DEVNULL,stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,env={},close_fds=True,bufsize=0)


def _run(argv,deadline):
    """Private fixed-call seam. Drain both pipes, including descendant-held EOF."""
    if argv not in _COMMANDS and argv not in _SYSTEMD.values():reject()
    _left(deadline);identity=_executable(argv[0])
    process=_spawn(argv)
    output=bytearray();errors=bytearray()
    try:
        with selectors.DefaultSelector() as selector:
            for stream,bound,data in ((process.stdout,2*1024*1024,output),(process.stderr,65536,errors)):
                os.set_blocking(stream.fileno(),False)
                selector.register(stream,selectors.EVENT_READ,(bound,data))
            while selector.get_map():
                ready=selector.select(_left(deadline))
                if not ready:reject()
                for key,_ in ready:
                    try:raw=os.read(key.fd,65536)
                    except BlockingIOError:continue
                    if not raw:selector.unregister(key.fileobj);continue
                    bound,data=key.data;data.extend(raw)
                    if len(data)>bound:reject()
        if process.wait(timeout=_left(deadline))!=0 or errors:reject()
        if _executable(argv[0])!=identity:reject()
        _left(deadline)
        return bytes(output)
    finally:
        primary=sys.exc_info()[1]
        failure=None
        def cleanup(action):
            nonlocal failure
            try:action()
            except Exception as error:
                if failure is None:failure=error
        alive=True
        try:alive=process.poll() is None
        except Exception as error:failure=error
        if alive:
            cleanup(process.kill);cleanup(lambda:process.wait(timeout=5))
        for stream in (process.stdout,process.stderr):cleanup(stream.close)
        if primary is None and failure is not None:raise failure


def read_systemd(name,deadline):
    """Two fixed metadata queries only, under both shared and per-call bounds."""
    _left(deadline)
    if type(name) is not str or name not in _SYSTEMD:reject()
    return _run(_SYSTEMD[name],min(deadline,time.monotonic()+3))


def _pairs(items):
    result={}
    for key,value in items:
        if key in result:reject()
        result[key]=value
    return result


def _routes(raw):
    value=json.loads(raw,object_pairs_hook=_pairs,parse_constant=lambda _:reject())
    if type(value) is not list or len(value)>2048 or any(type(row) is not dict for row in value):reject()
    return sorted(value,key=lambda row:json.dumps(row,sort_keys=True,separators=(',',':'),allow_nan=False))


def firewall_hash(raw):
    """Ignore generated timestamps/chain counters; preserve every rule byte/order."""
    material=[];table=None;seen=set()
    for line in raw.splitlines():
        if not line.strip():continue
        if re.fullmatch(rb'# Generated by (?:ip6?tables-save) v[^\r\n]+ on [^\r\n]+',line):continue
        if re.fullmatch(rb'# Completed on [^\r\n]+',line):continue
        if line.startswith(b'*'):
            if table is not None or not re.fullmatch(rb'\*[^\s]+',line) or line in seen:reject()
            table=line;seen.add(line)
        elif line==b'COMMIT':
            if table is None:reject()
            table=None
        elif not line.startswith(b'#') and table is None:reject()
        line=re.sub(rb'^(:[^\s]+ [^\s]+ )\[[0-9]+:[0-9]+\]$',rb'\1[COUNTERS]',line)
        material.append(line)
    if table is not None:reject()
    return hashlib.sha256(b'\n'.join(material)).hexdigest()


def _forward(path):
    fd=os.open(path,os.O_RDONLY|os.O_NOFOLLOW|os.O_NONBLOCK)
    try:raw=os.read(fd,17)
    finally:os.close(fd)
    if raw not in (b'0\n',b'1\n',b'0',b'1'):reject()
    return int(raw)


def capture_network(deadline):
    """One complete pass; caller compares independent passes under one deadline."""
    _left(deadline)
    netns=os.readlink('/proc/self/ns/net');mountns=os.readlink('/proc/self/ns/mnt')
    if not re.fullmatch(r'net:\[[0-9]+\]',netns) or not re.fullmatch(r'mnt:\[[0-9]+\]',mountns):reject()
    # Preflight all binaries before any command: missing IPv6 coverage never passes.
    identities={command[0]:_executable(command[0]) for command in _COMMANDS}
    routes4=_routes(_run(_COMMANDS[0],deadline));routes6=_routes(_run(_COMMANDS[1],deadline))
    firewall4=firewall_hash(_run(_COMMANDS[2],deadline));firewall6=firewall_hash(_run(_COMMANDS[3],deadline))
    forwards=[_forward(path) for path in _FORWARD]
    if (os.readlink('/proc/self/ns/net')!=netns or os.readlink('/proc/self/ns/mnt')!=mountns
            or any(_executable(path)!=identity for path,identity in identities.items())):reject()
    _left(deadline)
    tools={path:dict(target=value[0],device=value[1],inode=value[2]) for path,value in identities.items()}
    return dict(profile=PROFILE,netns=netns,mountns=mountns,tools=tools,routes4=routes4,routes6=routes6,
        ipForward4=forwards[0],ipForward6=forwards[1],firewall4=firewall4,firewall6=firewall6)
