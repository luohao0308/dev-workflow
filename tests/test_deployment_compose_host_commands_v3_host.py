class ProjectionTests(unittest.TestCase):
    def test_security_agent_rule_changes_remain_visible_across_frontend_stop(self):
        endpoint = b'-A PREROUTING -d 172.18.0.2/32 ! -i br-aaaaaaaaaaaa -j DROP'
        jump = b'-A INPUT -j YJ-FIREWALL-INPUT'
        ban = b'-A YJ-FIREWALL-INPUT -s 192.0.2.41/32 -p tcp -m tcp --dport 22 -j REJECT --reject-with icmp-port-unreachable'
        unrelated = b'-A FORWARD -j DROP'

        def snapshot(*rules, running, project_bans=False):
            raw = b'\n'.join((b'*raw', *((endpoint,) if running else ()), b'COMMIT',
                              b'*filter', b':YJ-FIREWALL-INPUT - [0:0]', *rules, b'COMMIT'))
            return host.firewall_hash(raw, expected_endpoint_rules=(endpoint,) if running else (),
                                      _project_transient_bans=project_bans)

        approved = snapshot(jump, ban, running=True)
        self.assertEqual(approved, snapshot(jump, ban, running=False))
        for changed in ((jump,), (ban,), (jump, ban, unrelated)):
            with self.subTest(rules=changed):
                self.assertNotEqual(approved, snapshot(*changed, running=True))
                self.assertNotEqual(approved, snapshot(*changed, running=False))
        projected = snapshot(jump, ban, running=True, project_bans=True)
        self.assertEqual(projected, snapshot(jump, running=False, project_bans=True))
        for changed in ((ban,), (jump, ban, unrelated), (jump, ban.replace(b'22', b'443'))):
            self.assertNotEqual(projected, snapshot(*changed, running=False, project_bans=True))

    def test_endpoint_rule_must_exist_once_and_preserves_other_rule_order(self):
        rule = b'-A PREROUTING -d 172.18.0.2/32 ! -i br-aaaaaaaaaaaa -j DROP'
        other = rule.replace(b'.2/32', b'.3/32')
        third = rule.replace(b'.2/32', b'.4/32')

        def raw(*rules):
            return b'\n'.join((b'*raw', *rules, b'COMMIT'))

        digest = host.firewall_hash(raw(rule, other, third), expected_endpoint_rules=(rule,))
        self.assertEqual(digest, host.firewall_hash(raw(other, third), expected_endpoint_rules=()))
        self.assertEqual(digest, host.firewall_hash(raw(other, rule, third), expected_endpoint_rules=(rule,)))
        self.assertNotEqual(digest, host.firewall_hash(raw(rule, third, other), expected_endpoint_rules=(rule,)))
        for rules in ((other,), (rule, rule), (rule, b'-A PREROUTING -j ACCEPT')):
            with self.assertRaises(ValueError):
                host.firewall_hash(raw(*rules), expected_endpoint_rules=(rule,))

    def test_firewall_normalizes_only_generated_times_and_chain_counters(self):
        first=b'# Generated by iptables-save v1.8.11 (nf_tables) on Mon\n*filter\n:INPUT ACCEPT [1:2]\n-A INPUT -m comment --comment "# Completed on keep" -j ACCEPT\nCOMMIT\n# Completed on Mon\n'
        second=first.replace(b'on Mon',b'on Tue').replace(b'[1:2]',b'[100:200]')
        self.assertEqual(host.firewall_hash(first),host.firewall_hash(second))
        for changed in (first.replace(b'INPUT ACCEPT',b'INPUT DROP'),first.replace(b'-j ACCEPT',b'-j DROP'),
                first.replace(b'on keep',b'on changed'),first+b'# operator note\n'):
            self.assertNotEqual(host.firewall_hash(first),host.firewall_hash(changed))
        self.assertNotEqual(host.firewall_hash(b'*x\n-A X -j A\n-A X -j B\nCOMMIT'),
            host.firewall_hash(b'*x\n-A X -j B\n-A X -j A\nCOMMIT'))
    def test_firewall_incomplete_or_ambiguous_tables_reject(self):
        for raw in (b'*filter\n:INPUT ACCEPT [0:0]\n',b'COMMIT\n',
                b'*filter\n*nat\nCOMMIT\n',b'*filter\nCOMMIT\n*filter\nCOMMIT\n',b'not-a-save-file'):
            with self.assertRaises(ValueError):host.firewall_hash(raw)
        self.assertEqual(host.firewall_hash(b''),host.firewall_hash(b'\n'))
    def test_routes_canonicalize_rows_but_keep_nested_order(self):
        self.assertEqual(host._routes(b'[{"dst":"b"},{"dst":"a"}]'),host._routes(b'[{"dst":"a"},{"dst":"b"}]'))
        self.assertNotEqual(host._routes(b'[{"nexthops":[1,2]}]'),host._routes(b'[{"nexthops":[2,1]}]'))
        for raw in (b'{}',b'[1]',b'[{"x":1,"x":2}]',b'[{"x":NaN}]',b'[{}'+b',{}'*2048+b']'):
            with self.assertRaises(ValueError):host._routes(raw)
    def test_capture_requires_complete_fixed_coverage(self):
        calls=[]
        def run(argv,deadline):calls.append(argv);return b'[]' if argv[0].endswith('/ip') else b'*filter\n:INPUT ACCEPT [0:0]\nCOMMIT\n'
        def link(path):return 'net:[1]' if path.endswith('/net') else 'mnt:[2]'
        with patch.object(host,'_executable',side_effect=lambda p:(p,1,2)),patch.object(host,'_run',side_effect=run),\
                patch.object(host.os,'readlink',side_effect=link),patch.object(host,'_forward',return_value=0):
            result=host.capture_network(time.monotonic()+5)
        self.assertEqual(calls,list(host._COMMANDS));self.assertEqual(result['netns'],'net:[1]')
        self.assertEqual(result['profile'],host.PROFILE);self.assertEqual(result['ipForward6'],0)
        self.assertEqual(result['tools']['/usr/sbin/iptables-save'],dict(target='/usr/sbin/iptables-save',device=1,inode=2))
        with patch.object(host,'_executable',side_effect=FileNotFoundError),patch.object(host,'_run') as invoke,\
                patch.object(host.os,'readlink',side_effect=link):
            with self.assertRaises(FileNotFoundError):host.capture_network(time.monotonic()+5)
            invoke.assert_not_called()
    def test_backend_identity_changes_snapshot_even_when_rules_are_empty(self):
        def link(path):return 'net:[1]' if path.endswith('/net') else 'mnt:[2]'
        def run(argv,deadline):return b'[]' if argv[0].endswith('/ip') else b''
        snapshots=[]
        for backend in ('nft','legacy'):
            with patch.object(host,'_executable',side_effect=lambda p:(p+'-'+backend,1,2)),\
                    patch.object(host,'_run',side_effect=run),patch.object(host.os,'readlink',side_effect=link),\
                    patch.object(host,'_forward',return_value=0):
                snapshots.append(host.capture_network(time.monotonic()+5))
        self.assertEqual(snapshots[0]['firewall4'],snapshots[1]['firewall4'])
        self.assertNotEqual(snapshots[0],snapshots[1])

    def test_cleanup_attempts_both_closes_and_preserves_primary(self):
        process=Mock();process.poll.return_value=None
        process.kill.side_effect=RuntimeError('kill-failed')
        process.wait.side_effect=RuntimeError('wait-failed')
        process.stdout.close.side_effect=RuntimeError('close-failed')
        with patch.object(host,'_spawn',return_value=process),\
                patch.object(host,'_executable',return_value=('trusted',1,2)),\
                patch.object(host.selectors,'DefaultSelector',side_effect=ValueError('primary-read-error')):
            with self.assertRaisesRegex(ValueError,'primary-read-error'):
                host._run(host._COMMANDS[0],time.monotonic()+5)
        process.kill.assert_called_once();process.wait.assert_called_once_with(timeout=5)
        process.stdout.close.assert_called_once();process.stderr.close.assert_called_once()

    def test_systemd_queries_are_fixed_and_have_short_shared_budget(self):
        deadline=time.monotonic()+10
        with patch.object(host,'_run',return_value=b'metadata') as run:
            for name in ('docker.service','docker.socket'):
                before=time.monotonic()
                self.assertEqual(host.read_systemd(name,deadline),b'metadata')
                argv,limited=run.call_args.args
                self.assertEqual(argv,host._SYSTEMD[name])
                self.assertLessEqual(limited,deadline);self.assertLessEqual(limited,before+3.1)
            for bad in ('other.service','docker.service;id',None,['docker.service']):
                with self.assertRaises(ValueError):host.read_systemd(bad,deadline)
            self.assertEqual(run.call_count,2)
        self.assertEqual(len(host._COMMANDS),4)

    def test_deadlines_reject_before_effects(self):
        for value in (True,float('nan'),float('inf'),time.monotonic()-1,time.monotonic()+40):
            with self.assertRaises(ValueError):host._left(value)


@unittest.skipUnless(os.name=='posix','POSIX pipe selectors required')
class PipeTests(unittest.TestCase):
    def invoke(self,code,timeout=3):
        real=subprocess.Popen
        self.process=None
        def spawn(argv):
            self.process=real([sys.executable,'-u','-c',code],stdin=subprocess.DEVNULL,
                stdout=subprocess.PIPE,stderr=subprocess.PIPE,bufsize=0,env={})
            return self.process
        with patch.object(host,'_spawn',side_effect=spawn),patch.object(host,'_executable',return_value=('trusted',1,2)):
            return host._run(host._COMMANDS[0],time.monotonic()+timeout)
    def test_simultaneous_stderr_does_not_deadlock_stdout(self):
        started=time.monotonic()
        with self.assertRaises(ValueError):self.invoke("import os;os.write(2,b'e'*60000);os.write(1,b'ok')")
        self.assertLess(time.monotonic()-started,2);self.assertEqual(self.process.returncode,0)
        self.assertTrue(self.process.stdout.closed and self.process.stderr.closed)
    def test_exit_zero_legacy_table_warning_is_incomplete_coverage(self):
        code="import os;os.write(1,b'*filter\\n:INPUT ACCEPT [0:0]\\nCOMMIT\\n');os.write(2,b'Warning: iptables-legacy tables present, use iptables-legacy-save to see them\\n')"
        with self.assertRaises(ValueError):self.invoke(code)
        self.assertEqual(self.process.returncode,0)
        self.assertTrue(self.process.stdout.closed and self.process.stderr.closed)

    def test_overflows_nonzero_and_timeout_reject_and_reap(self):
        for code in ("import os;os.write(1,b'x'*(2*1024*1024+1))", "import os;os.write(2,b'x'*65537)", "raise SystemExit(2)"):
            with self.subTest(code=code),self.assertRaises(ValueError):self.invoke(code)
            self.assertIsNotNone(self.process.poll())
        started=time.monotonic()
        with self.assertRaises(ValueError):self.invoke('import time;time.sleep(30)',timeout=.1)
        self.assertLess(time.monotonic()-started,2);self.assertIsNotNone(self.process.poll())
    def test_systemd_metadata_uses_same_real_bounded_pipe_reader(self):
        real=subprocess.Popen
        def spawn(argv):
            self.assertEqual(argv,host._SYSTEMD['docker.service'])
            return real([sys.executable,'-c',"print('Id=docker.service')"],stdin=subprocess.DEVNULL,
                stdout=subprocess.PIPE,stderr=subprocess.PIPE,bufsize=0,env={})
        with patch.object(host,'_spawn',side_effect=spawn),\
                patch.object(host,'_executable',return_value=('trusted',1,2)):
            self.assertEqual(host.read_systemd('docker.service',time.monotonic()+5),b'Id=docker.service\n')

    def test_spawn_fixed_environment_and_no_shell(self):
        with patch.object(host.subprocess,'Popen',return_value='process') as spawn:
            self.assertEqual(host._spawn(host._COMMANDS[0]),'process')
        self.assertEqual(spawn.call_args.kwargs['env'],{})
        self.assertNotIn('shell',spawn.call_args.kwargs)


